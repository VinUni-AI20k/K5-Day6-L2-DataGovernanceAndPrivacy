"""T08 self-check on the team's hand-labelled gold set (NOT the instructor's ground truth).

    python -m tools.t08_selfcheck                       # -> reports/t08_selfcheck.md

Scores every run with the official evaluator (src/metrics/tracks.py::eval_t08) and adds what the
evaluator does not print: Wilson intervals, per-case slices, policy ablations, and a sensitivity
analysis that re-scores each run after flipping the two labelling assumptions we could not verify
(A1 legal hold inherited, A3 shared artefact requested by every subject). Never reads fixtures/*/gt/.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
import tempfile
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.metrics.tracks import eval_t08  # noqa: E402
from src.t08_policy import build_plan  # noqa: E402

KEY = ["request_id", "artefact_id"]


def wilson(k: float, n: float, z: float = 1.96) -> tuple[float, float] | None:
    if not n:
        return None
    p = k / n
    centre, half = p + z * z / (2 * n), z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return max(0.0, (centre - half) / (1 + z * z / n)), min(1.0, (centre + half) / (1 + z * z / n))


def score(gold: pd.DataFrame, pred: pd.DataFrame, tmp: Path) -> dict:
    """Official evaluator on in-memory frames (audit completeness is scored separately, on the run folder)."""
    g, p = tmp / "gold.csv", tmp / "pred" / "actions.csv"
    p.parent.mkdir(exist_ok=True)
    gold[KEY + ["expected_action"]].to_csv(g, index=False)
    pred[KEY + ["action"]].to_csv(p, index=False)
    return {m.name: m for m in eval_t08(g, p, {}).metrics if m.slice == "all"}


def frac(m) -> str:
    if m.value is None:
        return "n/a"
    ci = wilson(m.numerator, m.denominator)
    return f"{m.value:.4f} ({int(m.numerator)}/{int(m.denominator)}; 95% CI {ci[0]:.3f}-{ci[1]:.3f})"


def scenarios(gold: pd.DataFrame) -> dict[str, pd.DataFrame]:
    no_a1 = gold.assign(expected_action=gold.expected_action.where(gold.label_case != "legal_hold_inherited", "delete"))
    no_a3 = gold.assign(expected_action=gold.expected_action.where(gold.label_case != "multi_subject_all_requested", "escalate"))
    both = no_a1.assign(expected_action=no_a1.expected_action.where(no_a1.label_case != "multi_subject_all_requested", "escalate"))
    return {
        "S0 gold as labelled (A1 + A3 hold)": gold,
        "S1 hold NOT inherited (26 pairs become delete)": no_a1,
        "S2 shared-by-all stays escalate (8 pairs become escalate)": no_a3,
        "S3 = S1 + S2": both,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gold", default="reports/t08_selflabel.csv")
    ap.add_argument("--input", default="fixtures/t08_deletion")
    ap.add_argument("--baseline", default="out/baseline/actions.csv")
    ap.add_argument("--poc", default="out/poc/actions.csv")
    ap.add_argument("--reviewed", default="out/poc_reviewed/actions.csv")
    ap.add_argument("--out", default="reports/t08_selfcheck.md")
    a = ap.parse_args(argv)

    gold = pd.read_csv(a.gold)
    fx = Path(a.input)
    graph = json.loads((fx / "data_graph.json").read_text(encoding="utf-8"))["artefacts"]
    reqs = json.loads((fx / "requests.json").read_text(encoding="utf-8"))
    typ = {x["artefact_id"]: x["type"] for x in graph}

    runs: dict[str, pd.DataFrame] = {}
    folders: dict[str, Path] = {}
    for name, path in (("Baseline (raw by filename)", a.baseline), ("PoC, machine only", a.poc), ("PoC + human review", a.reviewed)):
        if Path(path).exists():
            runs[name] = pd.read_csv(path)[KEY + ["action"]]
            folders[name] = Path(path)
        else:
            print(f"[selfcheck] skipped {name}: {path} not found", file=sys.stderr)
    if not runs:
        print("[selfcheck] no run outputs found; run the baseline and the PoC first", file=sys.stderr)
        return 2

    def variant(**kw) -> pd.DataFrame:
        return pd.DataFrame(build_plan(graph, reqs, **kw))[KEY + ["action"]]

    ablations = {
        "PoC rules (reference)": variant(),
        "V1 inherit_hold = false": variant(inherit_hold=False),
        "V2 no rows for other people's derived data": variant(include_derived_other_subject=False),
        "V3 delete everything found by lineage": variant().assign(action="delete"),
    }

    out = ["# T08 self-check (generated by `python -m tools.t08_selfcheck` - do not edit by hand)", "",
           f"Gold set: `{a.gold}`, N = {len(gold)} pairs, labelled by the team before the first PoC run. "
           "It is **not** the instructor's ground truth and it shares assumptions A1-A5 with the policy "
           "(see `reports/metric_contract.md`).", "",
           "Gold label counts: " + ", ".join(f"{k} = {v}" for k, v in gold.expected_action.value_counts().items()) + ".", ""]

    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        out += ["## 1. Runs on the gold set (official evaluator)", "",
                "| Run | Rows | Deletion Completeness | False-delete count | Exception handling accuracy | Audit trace completeness |",
                "|---|---|---|---|---|---|"]
        for name, pred in runs.items():
            m = score(gold, pred, tmp)
            full = {x.name: x for x in eval_t08(Path(a.gold), folders[name], {}).metrics if x.slice == "all"}
            au = full.get("Audit trace completeness")
            out.append(f"| {name} | {len(pred)} | {frac(m['Deletion Completeness'])} | {int(m['False-delete count'].value)} | "
                       f"{frac(m['Exception handling accuracy'])} | "
                       + (f"{au.value:.4f} ({int(au.numerator)}/{int(au.denominator)})" if au else "no audit log") + " |")

        out += ["", "## 2. Slices by labelled case (pairs handled exactly as labelled / pairs)", "",
                "| label_case | expected | N | " + " | ".join(runs) + " |", "|---|---|---|" + "---|" * len(runs)]
        for case, grp in gold.groupby("label_case", sort=True):
            cells = []
            for pred in runs.values():
                m = grp.merge(pred, on=KEY, how="left")
                cells.append(f"{int((m.action == m.expected_action).sum())}/{len(m)}")
            out.append(f"| {case} | {grp.expected_action.iloc[0]} | {len(grp)} | " + " | ".join(cells) + " |")

        out += ["", "## 3. Identity embeddings of the requesters that are still present", "",
                "The track's second failure mode: the raw file is gone but the embedding still identifies the person. "
                "Counted over gold pairs whose artefact is an `embedding`.", "",
                "| Run | Embeddings not deleted | Of which labelled must-delete |", "|---|---|---|"]
        emb = gold[gold.artefact_id.map(typ) == "embedding"]
        for name, pred in runs.items():
            m = emb.merge(pred, on=KEY, how="left")
            left = m[m.action != "delete"]
            out.append(f"| {name} | {len(left)}/{len(m)} | {int((left.expected_action == 'delete').sum())} |")

        out += ["", "## 4. Ablation (policy variants, no human review)", "",
                "| Variant | Rows | Deletion Completeness | False-delete count | Exception handling accuracy |", "|---|---|---|---|---|"]
        for name, pred in ablations.items():
            m = score(gold, pred, tmp)
            out.append(f"| {name} | {len(pred)} | {frac(m['Deletion Completeness'])} | {int(m['False-delete count'].value)} | "
                       f"{frac(m['Exception handling accuracy'])} |")

        out += ["", "## 5. Sensitivity to the two unverified labelling assumptions", "",
                "Each cell: Deletion Completeness / False-delete count / Exception handling accuracy, "
                "after re-labelling the gold set as the scenario says.", ""]
        cols = {**runs, "V1 inherit_hold = false": ablations["V1 inherit_hold = false"]}
        out += ["| Scenario | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
        for sname, g in scenarios(gold).items():
            cells = []
            for pred in cols.values():
                m = score(g, pred, tmp)
                dc, ex = m["Deletion Completeness"], m["Exception handling accuracy"]
                cells.append(f"{dc.value:.3f} / {int(m['False-delete count'].value)} / {ex.value:.3f}")
            out.append(f"| {sname} | " + " | ".join(cells) + " |")

    out += ["", "Reading guide: a False-delete count above 0 means data that should have been kept was destroyed, "
            "which cannot be undone; a completeness below 1 means a deletion is still owed and can be done later.", ""]
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
